/** Server retcode → MQL4 error code. */
export const rcToErr4 = (rc: number, pending: boolean): number =>
  rc === RC.INVALID_PRICE ? (pending ? 130 : 129) :
  ({ [RC.INVALID_VOLUME]: 131, [RC.INVALID_CLOSE_VOLUME]: 131, [RC.INVALID_STOPS]: 130, [RC.NO_MONEY]: 134, [RC.REQUOTE]: 138,
    [RC.INVALID_EXPIRATION]: 3, [RC.NO_CHANGES]: 1, [RC.POSITION_CLOSED]: 4108, [RC.INVALID]: 3, [RC.INVALID_ORDER]: 3,
    [RC.TRADE_DISABLED]: 133, [RC.MARKET_CLOSED]: 132 } as Record<number, number>)[rc] ?? 2;

