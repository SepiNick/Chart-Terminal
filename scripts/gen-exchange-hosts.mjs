// Generates android/app/src/main/java/app/chartterminal/ExchangeHosts.java: the https hosts the native exchange proxy may reach.
// Sources: every ccxt exchange's `urls.api` (not urls.www / urls.test) plus EXTRA below. Public DNS names only.
// Usage: node scripts/gen-exchange-hosts.mjs          (rewrite the file)
//        node scripts/gen-exchange-hosts.mjs --check  (exit 1 if the checked-in file is stale)
import ccxt from 'ccxt';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(root, 'android/app/src/main/java/app/chartterminal/ExchangeHosts.java');

// Curated: hosts ccxt reaches through templates/options or that the app needs beyond urls.api.
const EXTRA = [
  'api.binance.com', 'api1.binance.com', 'api2.binance.com', 'api3.binance.com', 'api4.binance.com', 'api-gcp.binance.com',
  'fapi.binance.com', 'dapi.binance.com', 'eapi.binance.com', 'papi.binance.com',
  'api.bybit.com', 'api.bytick.com', 'www.okx.com', 'aws.okx.com', 'api.kraken.com', 'futures.kraken.com',
  'api.coinbase.com', 'api.exchange.coinbase.com', 'api.international.coinbase.com',
  'api.kucoin.com', 'api-futures.kucoin.com', 'api-broker.kucoin.com', 'api.bitget.com', 'api.gateio.ws',
  'api.mexc.com', 'contract.mexc.com', 'api.huobi.pro', 'api-aws.huobi.pro', 'api.hbdm.com', 'api.hbdm.vn',
  'api-pub.bitfinex.com', 'api.bitfinex.com', 'www.bitstamp.net', 'api.gemini.com', 'api.crypto.com', 'deriv-api.crypto.com',
  'www.deribit.com', 'api.phemex.com', 'open-api.bingx.com', 'api.lbank.info', 'lbkperp.lbank.com', 'whitebit.com',
  'api.upbit.com', 'api.bithumb.com', 'api.poloniex.com', 'api.bitvavo.com', 'api.hyperliquid.xyz', 'api.bitso.com',
];
// Already served by MainActivity.isAllowedHost (checked first), so the proxy must not claim them.
const EXCLUDE = new Set(['data-api.binance.vision', 'data-stream.binance.vision']);

const urlsIn = (v, ex, acc) => {
  if (typeof v === 'string') {
    // fill {hostname}-style templates from the instance; skip anything still templated
    const s = v.replace(/\{(\w+)\}/g, (m, k) => (typeof ex[k] === 'string' ? ex[k] : m));
    if (!s.includes('{')) acc.push(s);
  } else if (v && typeof v === 'object') for (const x of Object.values(v)) urlsIn(x, ex, acc);
};

const DNS = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;
export const hostOf = (s) => {
  let u;
  try { u = new URL(s); } catch { return null; }
  if (u.protocol !== 'https:' || u.username || u.password || (u.port && u.port !== '443')) return null;
  const h = u.hostname.toLowerCase();
  return DNS.test(h) && !/^[0-9.]+$/.test(h) && !/^(\d+\.){3}\d+$/.test(h) && h !== 'localhost' && !h.endsWith('.localhost') ? h : null;
};

const found = new Set(EXTRA);
for (const id of ccxt.exchanges) {
  let ex;
  try { ex = new ccxt[id](); } catch { continue; }
  const acc = [];
  urlsIn(ex.urls?.api, ex, acc);
  for (const s of acc) { const h = hostOf(s); if (h) found.add(h); }
}
const hosts = [...found].filter((h) => hostOf('https://' + h) && !EXCLUDE.has(h)).sort();

const src = `package app.chartterminal;

// GENERATED by scripts/gen-exchange-hosts.mjs (ccxt ${ccxt.version} urls.api + curated extras). Do not edit by hand.
// Regenerate: node scripts/gen-exchange-hosts.mjs   (verify: node scripts/gen-exchange-hosts.mjs --check)
// Public https DNS names only; hosts MainActivity.isAllowedHost already serves are excluded.
final class ExchangeHosts {
    private ExchangeHosts() {}

    static final String[] ALL = {
${hosts.map((h) => `        "${h}",`).join('\n')}
    };
}
`;

if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== src) { console.error('ExchangeHosts.java is stale; run node scripts/gen-exchange-hosts.mjs'); process.exit(1); }
  console.log(`ExchangeHosts.java up to date (${hosts.length} hosts)`);
} else {
  writeFileSync(OUT, src);
  console.log(`wrote ${hosts.length} hosts`);
}
